"use client";

import { AVAILABILITY_LABEL, QUALITY_LABEL, type Compatibility, type Quality } from "@/data/demo";
import type { SimulatedOffer } from "@/engine/offers";

type Availability = SimulatedOffer["availability"];

export function CompatibilityChip({ kind }: { kind: Compatibility }) {
  const map: Record<Compatibility, { label: string; cls: string }> = {
    compatible: { label: "Compatible", cls: "border-sage-400/50 text-sage-400" },
    partial: { label: "Partial", cls: "border-amber-400/50 text-amber-400" },
    forming: { label: "Forming", cls: "border-cyan-400/50 text-cyan-400" },
  };
  return <span className={`tick border px-1.5 py-0.5 ${map[kind].cls}`}>{map[kind].label}</span>;
}

export function QualityChip({ quality }: { quality: Quality }) {
  return <span className="tick border border-ink-600 px-1.5 py-0.5 text-fog-300">Quality · {QUALITY_LABEL[quality]}</span>;
}

export function AvailabilityChip({ availability }: { availability: Availability }) {
  const cls: Record<Availability, string> = {
    in_stock: "text-sage-400",
    limited: "text-amber-400",
    made_to_order: "text-cyan-400",
  };
  return <span className={`tick ${cls[availability]}`}>{AVAILABILITY_LABEL[availability]}</span>;
}

/** Marks from the deterministic offer ranking. */
export function EnginePickChip({ score }: { score: number }) {
  return (
    <span className="tick border border-sage-400/60 bg-sage-400/10 px-1.5 py-0.5 text-sage-400">
      ENGINE PICK · score {score.toFixed(2)}
    </span>
  );
}

export function RankChip({ label, rank }: { label: string; rank: number }) {
  return (
    <span className="tick border border-ink-600 px-1.5 py-0.5 text-fog-300">
      {label} #{rank}
    </span>
  );
}

/* ── Phase 3: trust indicators — what generated this output? ── */

/**
 * One of the three honest origin labels. Never generic:
 *   - "ai"        a real model call succeeded and passed validation
 *   - "engine"    deterministic Phase 2 computation
 *   - "fallback"  deterministic rule engine standing in for an unavailable model
 *   - "sim"       simulated seller strategy (not a real market)
 */
export type TrustOrigin = "ai" | "engine" | "fallback" | "sim" | "user";

const TRUST: Record<TrustOrigin, { label: string; cls: string; title: string }> = {
  ai: { label: "AI", cls: "border-violet-400/60 text-violet-300", title: "Generated by a real AI model call, then validated against engine facts." },
  engine: { label: "ENGINE", cls: "border-sage-400/60 text-sage-400", title: "Computed by the deterministic matching engine — the source of truth." },
  fallback: { label: "FALLBACK · RULES", cls: "border-amber-400/60 text-amber-400", title: "Deterministic rule engine used because no AI model was available. Not model output." },
  sim: { label: "SIM", cls: "border-cyan-400/50 text-cyan-400", title: "Simulated seller strategy quote for the demo — not a real vendor." },
  user: { label: "YOU", cls: "border-ink-500 text-fog-200", title: "Stated directly by you." },
};

export function TrustChip({ origin, prefix }: { origin: TrustOrigin; prefix?: string }) {
  const t = TRUST[origin];
  return (
    <span title={t.title} className={`tick border px-1.5 py-0.5 ${t.cls}`}>
      {prefix ? `${prefix} · ` : ""}
      {t.label}
    </span>
  );
}
