"use client";

import { useMarket } from "@/state/store";

/**
 * Derived, inline metrics — deliberately NOT a row of identical stat cards.
 * Every number comes from the matching engine's computed market state.
 */
export function MetricsStrip() {
  const { state } = useMarket();

  const buyers = state.buyers.length;
  const matched = state.buyers.length - state.computed.pool.length;
  const poolCount = state.computed.pool.length;
  const groups = state.computed.groups.length;
  const offers = state.computed.offers.length;
  const picks = state.computed.offers.filter((o) => o.recommended).length;

  return (
    <dl className="flex flex-wrap gap-x-10 gap-y-4 border-y border-ink-700 py-4">
      <Metric index="01" label="Buyers participating" value={buyers} note={`${matched} grouped · ${poolCount} still forming`} accent="#E9EDF4" />
      <Metric index="02" label="Demand groups standing" value={groups} note="validated · min-linkage joined" accent="#FF6B5B" />
      <Metric index="03" label="Eligible simulated offers" value={offers} note="generated by three strategy profiles" accent="#5CC8DC" />
      <Metric index="04" label="Engine picks" value={picks} note="one ranked recommendation per group" accent="#E0A43C" />
    </dl>
  );
}

function Metric({ index, label, value, note, accent }: { index: string; label: string; value: number; note: string; accent: string }) {
  return (
    <div className="min-w-[150px]">
      <dt className="tick text-fog-500">
        <span style={{ color: accent }}>{index}</span> / {label}
      </dt>
      <dd className="mt-1 font-display text-3xl font-bold leading-none text-fog-100">
        {String(value).padStart(2, "0")}
      </dd>
      <p className="mt-1.5 font-mono text-[10px] text-fog-400">{note}</p>
    </div>
  );
}
